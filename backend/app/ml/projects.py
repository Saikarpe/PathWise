"""Project and assessment synthesis.

The catalogue ships courses, not projects — but a learning path made only of
courses teaches recognition, not capability. Each phase therefore gets a
synthesised **project** whose deliverables are derived from the actual tools and
skills the phase's courses teach, plus **assessments** at the two points where
they change a decision:

* a *placement check* in phase 1, but only when the planner waived lower tiers on
  the strength of the learner's self-reported level. It is the cheapest way to
  falsify that assumption before it costs weeks.
* a *final evaluation* after the last phase, scoped to the skills the plan
  claimed it would deliver.

Nothing here is generated by a language model. Deliverables come from the phase's
own ``tools_covered`` and ``skills_taught`` values, and the artifact noun comes
from a keyword table over track names, so a Structural Analysis phase asks for a
load analysis report and a Web Development phase asks for a deployed app. That
keeps the output specific and reproducible with no API key.
"""
