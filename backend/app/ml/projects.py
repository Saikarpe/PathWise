def synthesize_phase_items(
    plan: "LearningPlan",
    cat: Catalog,
    goal: GoalInterpretation,
    chosen: list[tuple[str, tuple[str, str], float]],
    waivers: list[dict] | None = None,
) -> None:
    """Append a project per phase, plus placement and final assessments.

    Mutates ``plan.items`` in place; the planner renumbers and schedules after.
    ``waivers`` is passed in rather than read from ``plan.analysis`` because the
    planner fills that in only once scheduling is done.
    """
    from app.ml.planner import PlanItem  # local import: planner imports this module

    if not plan.phases:
        return

    primary_track = chosen[0][0] if chosen else (goal.ranked_tracks[0][0] if goal.ranked_tracks else "")
    goal_label = _goal_label(goal, primary_track)

    for phase in plan.phases:
        courses = [i for i in plan.items if i.phase_index == phase.index and i.item_type == "course"]
        if not courses:
            continue

        tier = int(min(c.meta.get("tier", phase.index) for c in courses))
        track = _phase_track(courses, primary_track)
        tools = _unique(t for c in courses for t in _tools_of(cat, c.course_id))[:5]
        skills = _unique(s for c in courses for s in c.skills)[:6]

        kind, intent = PROJECT_KIND.get(tier, PROJECT_KIND[1])
        artifact, deliverables = _artifact_for(track)

        plan.items.append(
            PlanItem(
                item_type="project",
                title=f"{kind}: {artifact} for {goal_label}",
                hours=PROJECT_HOURS.get(tier, 12.0),
                phase_index=phase.index,
                phase_name=phase.name,
                origin="project",
                sort_hint=_HINT_PROJECT,
                skills=skills,
                rationale=(
                    f"{intent}. Courses teach recognition; building "
                    f"{'a' if artifact[0] not in 'aeiou' else 'an'} {artifact} is what "
                    f"proves you can apply {', '.join(skills[:3]) or 'these skills'}."
                ),
                meta={
                    "kind": kind,
                    "artifact": artifact,
                    "deliverables": list(deliverables),
                    "tools": tools,
                    "track": track,
                    "tier": tier,
                    "evaluation": _evaluation_criteria(skills),
                },
            )
        )

    # ---- placement check: only if the planner waived tiers ----
    if waivers:
        skipped = _unique(f"{w['track']} ({w['difficulty']})" for w in waivers)
        first = plan.phases[0]
        plan.items.append(
            PlanItem(
                item_type="assessment",
                title="Placement check: confirm the fundamentals we skipped",
                hours=1.5,
                phase_index=first.index,
                phase_name=first.name,
                origin="assessment",
                sort_hint=_HINT_PLACEMENT,
                skills=_phase_skills(plan, first.index)[:6],
                rationale=(
                    "Your path starts above the entry level because of how you described "
                    "your experience. This check falsifies that assumption in 90 minutes "
                    "instead of three weeks. Score below 70% and we will add the skipped "
                    f"material back: {', '.join(skipped[:3])}."
                ),
                meta={
                    "kind": "Placement check",
                    "pass_threshold": 0.7,
                    "waived": waivers,
                    "on_fail": "Re-plan with the skipped tiers restored.",
                },
            )
        )

    # ---- final evaluation over everything the plan promised ----
    last = plan.phases[-1]
    promised = _unique(
        s for i in plan.items if i.item_type == "course" for s in i.skills
    )[:10]
    plan.items.append(
        PlanItem(
            item_type="assessment",
            title=f"Final evaluation: {goal_label} readiness",
            hours=2.0,
            phase_index=last.index,
            phase_name=last.name,
            origin="assessment",
            sort_hint=_HINT_FINAL,
            skills=promised,
            rationale=(
                "Checks the specific competencies this path set out to build, so "
                "'finished' means demonstrated rather than merely watched."
            ),
            meta={
                "kind": "Final evaluation",
                "pass_threshold": 0.75,
                "covers_skills": promised,
                "sections": _evaluation_criteria(promised),
            },
        )
    )


