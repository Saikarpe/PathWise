def _artifact_for(track: str) -> tuple[str, tuple[str, str, str]]:
    lowered = (track or "").lower()
    for keywords, artifact, deliverables in ARTIFACT_RULES:
        if any(k in lowered for k in keywords):
            return artifact, deliverables
    return _DEFAULT_ARTIFACT


def _goal_label(goal: GoalInterpretation, primary_track: str) -> str:
    """A short human label for what the learner is aiming at."""
    if goal.careers:
        return goal.careers[0].title()
    return primary_track or "your goal"


def _phase_track(courses: list["PlanItem"], primary_track: str) -> str:
    """The track a phase's project should be framed around.

    Uses the phase's *ladder* courses only. A gap top-up is a supporting course
    that happens to sort first, and letting it choose the artifact once framed a
    data-science phase as "build a deployment pipeline".
    """
    ladder = [c for c in courses if c.origin in ("ladder", "prerequisite")]
    for candidate in (ladder, courses):
        counts: dict[str, int] = {}
        for course in candidate:
            track = course.meta.get("track")
            if track:
                counts[track] = counts.get(track, 0) + 1
        if counts:
            if primary_track in counts:
                return primary_track  # the goal's strongest ladder wins ties
            return max(counts.items(), key=lambda kv: kv[1])[0]
    return primary_track


def _tools_of(cat: Catalog, course_id: str | None) -> list[str]:
    if not course_id:
        return []
    pos = cat.pos(course_id)
    return list(cat.df.iloc[pos]["tools_covered"]) if pos is not None else []


def _phase_skills(plan: "LearningPlan", phase_index: int) -> list[str]:
    """Skills taught by the courses of one phase, read from items directly."""
    return _unique(
        s
        for i in plan.items
        if i.phase_index == phase_index and i.item_type == "course"
        for s in i.skills
    )


def _evaluation_criteria(skills: list[str]) -> list[str]:
    """Turn skills into checkable criteria rather than vague objectives."""
    criteria = [f"Demonstrates {s} on a task you have not seen before" for s in skills[:4]]
    criteria.append("Work is reproducible from the artefacts alone")
    criteria.append("Limitations and next steps are stated explicitly")
    return criteria


def _unique(values) -> list[str]:
    seen: dict[str, None] = {}
    for v in values:
        seen.setdefault(v, None)
    return list(seen)
